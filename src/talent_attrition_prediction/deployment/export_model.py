"""Export one registered MLflow model as a self-contained deployment bundle."""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import tempfile
from dataclasses import asdict
from datetime import UTC, datetime
from pathlib import Path

import mlflow

from talent_attrition_prediction.deployment.paths import REPOSITORY_ROOT
from talent_attrition_prediction.serving.config import ServingSettings
from talent_attrition_prediction.serving.service import ModelService

DEFAULT_OUTPUT_DIR = REPOSITORY_ROOT / ".deployment"
_BUNDLE_MARKER = ".talent-deployment-bundle"
_GENERATED_ENTRIES = {
    _BUNDLE_MARKER,
    "model",
    "model-descriptor.json",
}


def export_model(
    *,
    model_uri: str,
    tracking_uri: str,
    output_dir: Path = DEFAULT_OUTPUT_DIR,
) -> Path:
    """Download, verify, and describe the exact model used by Cloud Run."""
    destination = _validated_destination(output_dir)
    _assert_safe_destination(destination)

    with (
        tempfile.TemporaryDirectory(
            prefix=".talent-deployment-staging-",
            dir=destination.parent,
        ) as staging_directory,
        tempfile.TemporaryDirectory(
            prefix=".talent-model-download-",
            dir=destination.parent,
        ) as download_directory,
    ):
        staging = Path(staging_directory) / "bundle"
        staging.mkdir()

        service = ModelService.load(
            model_uri=model_uri,
            tracking_uri=tracking_uri,
        )
        downloaded = Path(
            mlflow.artifacts.download_artifacts(
                artifact_uri=model_uri,
                dst_path=download_directory,
            )
        )
        model_path = staging / "model"
        shutil.copytree(downloaded, model_path)

        # Fail before replacing an earlier valid bundle if the new artifact is
        # incomplete or cannot be loaded outside the registry.
        mlflow.pyfunc.load_model(str(model_path))
        bundle_sha256 = _directory_sha256(model_path)

        descriptor_path = staging / "model-descriptor.json"
        descriptor_path.write_text(
            json.dumps(
                {
                    "schema_version": 1,
                    "exported_at_utc": datetime.now(UTC).isoformat(),
                    "bundle_sha256": bundle_sha256,
                    "model": asdict(service.descriptor),
                },
                indent=2,
                sort_keys=True,
            )
            + "\n",
            encoding="utf-8",
        )
        (staging / _BUNDLE_MARKER).write_text(
            "Generated by talent-export-model. Do not edit.\n",
            encoding="utf-8",
        )
        _replace_destination(staging, destination)
    return destination / "model-descriptor.json"


def _validated_destination(path: Path) -> Path:
    destination = path.expanduser().resolve()
    if destination == REPOSITORY_ROOT or not destination.is_relative_to(
        REPOSITORY_ROOT
    ):
        raise ValueError("Deployment output must be a child of the repository.")
    return destination


def _assert_safe_destination(destination: Path) -> None:
    """Refuse to recursively replace any directory containing other work."""
    if not destination.exists():
        destination.parent.mkdir(parents=True, exist_ok=True)
        return
    if not destination.is_dir():
        raise ValueError("Deployment output must be a directory.")
    unexpected = {item.name for item in destination.iterdir()} - _GENERATED_ENTRIES
    if unexpected:
        names = ", ".join(sorted(unexpected))
        raise ValueError(
            "Refusing to replace a deployment directory containing unrelated "
            f"files: {names}"
        )


def _replace_destination(staging: Path, destination: Path) -> None:
    """Replace a generated bundle and restore the previous one on failure."""
    backup_root = Path(
        tempfile.mkdtemp(
            prefix=".talent-deployment-backup-",
            dir=destination.parent,
        )
    )
    backup = backup_root / "bundle"
    try:
        if destination.exists():
            destination.rename(backup)
        try:
            staging.rename(destination)
        except OSError:
            if backup.exists() and not destination.exists():
                backup.rename(destination)
            raise
    finally:
        shutil.rmtree(backup_root, ignore_errors=True)


def _directory_sha256(directory: Path) -> str:
    digest = hashlib.sha256()
    for path in sorted(item for item in directory.rglob("*") if item.is_file()):
        digest.update(path.relative_to(directory).as_posix().encode())
        digest.update(b"\0")
        with path.open("rb") as file:
            for chunk in iter(lambda: file.read(1024 * 1024), b""):
                digest.update(chunk)
    return digest.hexdigest()


def _build_parser() -> argparse.ArgumentParser:
    defaults = ServingSettings.load()
    parser = argparse.ArgumentParser(
        description="Export the registered MLflow candidate for container deployment."
    )
    parser.add_argument("--model-uri", default=defaults.model_uri)
    parser.add_argument("--tracking-uri", default=defaults.tracking_uri)
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=DEFAULT_OUTPUT_DIR,
    )
    return parser


def main() -> None:
    args = _build_parser().parse_args()
    descriptor = export_model(
        model_uri=args.model_uri,
        tracking_uri=args.tracking_uri,
        output_dir=args.output_dir,
    )
    payload = json.loads(descriptor.read_text(encoding="utf-8"))
    print(f"Exported deployment model to {descriptor.parent}")
    print(f"Model bundle SHA-256: {payload['bundle_sha256']}")


if __name__ == "__main__":
    main()
